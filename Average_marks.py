# simple_average.py

# 1. Define a list of student marks
marks = [85, 92, 78, 90, 88]

# 2. Calculate the total sum of all marks
total_sum = sum(marks)

# 3. Find out how many students (or marks) there are
number_of_students = len(marks)

# 4. Calculate the average
# Average = Total Sum / Number of Items
average_marks = total_sum / number_of_students

# 5. Output the result
print("Student Marks:", marks)
print(f"The average marks of the students is: {average_marks}")